import SwiftUI

/// Renders a shareable PDF report of the fuel log.
@MainActor
enum PDFExportService {

    /// Creates a one-page PDF summary report and returns its temporary file URL.
    static func createReportPDF(entries: [FuelEntry], summary: FuelSummary, settings: AppSettings) -> URL? {
        let fileName = "oktan-report-\(Date().formatted(.iso8601.year().month().day())).pdf"
        let url = FileManager.default.temporaryDirectory.appendingPathComponent(fileName)

        let renderer = ImageRenderer(content: ReportPDFView(entries: entries, summary: summary, settings: settings))
        // US Letter width; height follows content.
        renderer.proposedSize = ProposedViewSize(width: 612, height: nil)

        var succeeded = false
        renderer.render { size, renderContent in
            var mediaBox = CGRect(origin: .zero, size: size)
            guard let pdfContext = CGContext(url as CFURL, mediaBox: &mediaBox, nil) else { return }
            pdfContext.beginPDFPage(nil)
            renderContent(pdfContext)
            pdfContext.endPDFPage()
            pdfContext.closePDF()
            succeeded = true
        }

        return succeeded ? url : nil
    }
}

/// The printable report layout. Kept intentionally simple and ink-friendly.
private struct ReportPDFView: View {
    let entries: [FuelEntry]
    let summary: FuelSummary
    let settings: AppSettings

    private var sortedEntries: [FuelEntry] {
        entries.sorted { $0.date < $1.date }
    }

    private var dateRangeText: String {
        guard let first = sortedEntries.first, let last = sortedEntries.last else { return "" }
        return "\(first.date.formatted(date: .abbreviated, time: .omitted)) – \(last.date.formatted(date: .abbreviated, time: .omitted))"
    }

    private var cyclesByEntryID: [UUID: FuelCycleService.Cycle] {
        Dictionary(uniqueKeysWithValues: FuelCycleService.completedCycles(from: entries)
            .map { ($0.id, $0) })
    }

    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            // Header
            HStack {
                VStack(alignment: .leading) {
                    Text("Oktan Fuel Report")
                        .font(.title.bold())
                    Text(dateRangeText)
                        .font(.subheadline)
                        .foregroundStyle(.secondary)
                }
                Spacer()
                Image(systemName: "fuelpump.fill")
                    .font(.title)
            }

            Divider()

            // Summary metrics
            Grid(alignment: .leading, horizontalSpacing: 24, verticalSpacing: 8) {
                GridRow {
                    metric("Total distance", settings.formatDistance(summary.totalDistance))
                    metric("Total fuel", settings.formatVolume(summary.totalLiters))
                }
                GridRow {
                    metric("Total spent", settings.formatCost(summary.totalCost))
                    metric("Fill-ups", "\(entries.count)")
                }
                GridRow {
                    metric("Avg efficiency", summary.averageLitersPer100KM.map { settings.formatEfficiency($0) } ?? "—")
                    metric("Avg cost", summary.averageCostPerKM.map { settings.formatCostPerDistance($0) } ?? "—")
                }
            }

            Divider()

            // Entry table
            Text("Fill-ups")
                .font(.headline)

            Grid(alignment: .leading, horizontalSpacing: 12, verticalSpacing: 4) {
                GridRow {
                    tableHeader("Date")
                    tableHeader("Station")
                    tableHeader("Fuel")
                    tableHeader("Cost")
                    tableHeader("Efficiency")
                }
                Divider()
                ForEach(sortedEntries) { entry in
                    GridRow {
                        Text(entry.date.formatted(date: .numeric, time: .omitted))
                        Text(entry.gasStation)
                        Text(settings.formatVolume(entry.totalLiters))
                        Text(settings.formatCost(entry.totalCost))
                        Text(cyclesByEntryID[entry.id].map { settings.formatEfficiency($0.litersPer100KM) } ?? "—")
                    }
                    .font(.caption)
                }
            }

            Spacer(minLength: 12)

            Text("Generated by Oktan on \(Date().formatted(date: .long, time: .shortened))")
                .font(.caption2)
                .foregroundStyle(.secondary)
        }
        .padding(36)
        .frame(width: 612, alignment: .topLeading)
        .background(Color.white)
        .foregroundStyle(Color.black)
        .environment(\.colorScheme, .light)
    }

    private func metric(_ label: String, _ value: String) -> some View {
        VStack(alignment: .leading, spacing: 2) {
            Text(label)
                .font(.caption)
                .foregroundStyle(.secondary)
            Text(value)
                .font(.headline)
        }
        .gridColumnAlignment(.leading)
    }

    private func tableHeader(_ text: String) -> some View {
        Text(text)
            .font(.caption.bold())
            .foregroundStyle(.secondary)
    }
}
